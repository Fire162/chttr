#!/usr/bin/env python3
"""Write docs/configuration.md from the commented default config in config.py.

    python3 scripts/gen-config-docs.py          # rewrite the file
    python3 scripts/gen-config-docs.py --check  # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from chttr.config import DEFAULT_CONFIG  # noqa: E402

OUT = ROOT / "docs" / "configuration.md"


def render() -> str:
    lines = [
        "# Configuration reference",
        "",
        "`~/.config/chttr/config.toml` (create it with `chttr config`; apply changes with",
        "`chttr reload`). Every key is optional; below are the defaults with their",
        "explanations, exactly as chttr writes them.",
        "",
        "<!-- generated by scripts/gen-config-docs.py from src/chttr/config.py; edit those -->",
        "",
    ]
    section, body = "", []

    def flush() -> None:
        if not section:                     # the file's own header comment
            return
        while body and not body[-1].strip():
            body.pop()
        lines.extend([f"## `[{section}]`", "", "```toml", f"[{section}]", *body, "```", ""])

    modes_started = False
    for raw in DEFAULT_CONFIG.splitlines():
        stripped = raw.strip()
        if stripped.startswith("[[modes]]"):
            if not modes_started:
                flush()
                section, body, modes_started = "", [], True
                lines.extend(["## `[[modes]]` (per-app modes)", "", "```toml"])
            lines.append(raw)
            continue
        if modes_started:
            lines.append(raw)
            continue
        if stripped.startswith("[") and stripped.endswith("]"):
            flush()
            section, body = stripped[1:-1], []
            continue
        body.append(raw)
    if modes_started:
        lines.extend(["```", ""])
    else:
        flush()
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/configuration.md is out of date: python3 scripts/gen-config-docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
